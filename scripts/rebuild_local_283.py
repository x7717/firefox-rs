#!/usr/bin/env python3
"""rebuild_local_283.py — восстановление хвоста локального worklog после
СНАПШОТ-ОТКАТА #79 (окно 283, прогноз окна 282 СБЫЛСЯ ТОЧНО: 'при откате
в окне 283 — #79, ШЕСТИДЕСЯТЫЙ пережитый'): конденсаты 189-279 из repo
WORKLOG.md + ПОЛНЫЕ записи 280/281/282 (все уже в repo WORKLOG.md —
запись 282 появилась однокоммитной формой f92d0dd окна 282). Локальный
worklog откатился к эре 188 (7810 строк, хвост = пре-регистрация окна
188 + фрагмент окна 213); repo откатился к эре окна 213 (97e1e53),
восстановлен ff-only до f92d0dd ДО запуска этого скрипта (урок 157)."""
import re
from pathlib import Path

REPO = Path("/home/z/my-project/firefox-rs/WORKLOG.md")
LOCAL = Path("/home/z/my-project/worklog.md")

raw = REPO.read_text(encoding="utf-8")
lines = raw.splitlines()

idx = []
for i, ln in enumerate(lines):
    m = re.match(r"^## 2026-1[01]-\d+, Окно (\d+) ", ln)
    if m and 189 <= int(m.group(1)) <= 279:
        idx.append((int(m.group(1)), i))
assert idx and idx[0][0] == 189, f"первый конденсат {idx[0][0]} != 189"
missing = [w for w in range(189, 280)
           if w not in (206, 207, 208, 229)
           and w not in (wno for wno, _ in idx)]
assert not missing, f"нет заголовков окон: {missing}"
assert idx[-1][0] == 279, f"последний конденсат {idx[-1][0]} != 279"

start280 = next(i for i, ln in enumerate(lines)
                if re.match(r"^## 2026-11-01, Окно 280 ", ln))
full280_282 = "\n".join(lines[start280:]).rstrip() + "\n"
assert "Окно 281" in full280_282 and "Окно 282" in full280_282

# защита: локальный worklog должен быть в эре 188 (без '##'-заголовков 189+)
local_raw = LOCAL.read_text(encoding="utf-8")
n_h = len(re.findall(r"^## ", local_raw, re.M))
hdrs = re.findall(r"^## .*Окно (\d+) ", local_raw, re.M)
bad = [h for h in hdrs if int(h) >= 189]
assert not bad, f"локальный worklog НЕ в эре 188: заголовки {bad}"
assert "ПРЕ-РЕГИСТРАЦИЯ ОКНА 188" in local_raw, "эра 188 не опознана"

out = []
out.append("<!-- REBUILD после СНАПШОТ-ОТКАТА #79 (старт 21:00-сессии окна 283):")
out.append("     repo в эру окна 213 (97e1e53, итерации 214-282 отсутствовали),")
out.append("     восстановлен ff-only ДВАДЦАТЬ ВОСЬМОЙ раз подряд (урок 157),")
out.append("     cron/ на месте (3 файла в git), хвост локального worklog потерян")
out.append("     (локальный worklog откатился к эре 188, последняя запись")
out.append("     эры окна 188 + фрагмент окна 213); восстановлен конденсатами")
out.append("     189-279 из repo WORKLOG.md (заголовки окон, ~600 символов каждое)")
out.append("     + ПОЛНЫЕ записи 280/281/282 из repo WORKLOG.md. -->")
for wno, i in idx:
    head = lines[i][:600]
    out.append(f"- {head}")
# окна 206/207/208/229 — без "##"-заголовков в repo WORKLOG, конденсаты вручную
out.append(
    "- [окно 206, конденсат] итерация 206: 194-й вердикт ТИХИЙ ПАРИТЕТ "
    "exit 0 БЕЗ заметки (ff7b23e копия-2 #204 vs 1e5aff2 #202, CLASSIC "
    "КРОСС-ЗАПИСНАЯ idx 205 vs 203, разброс 3.2 УЗКИЙ; откат #20 — ПЯТЫЙ "
    "ПОДРЯД #16-#20; ДУБЛЬ-SCHEDULE #2 — ff7b23e x2 ОБА push, белый список "
    "6->7 (+ff7b23e); SELF-PAIR AVOIDANCE DEDUP RUN — data204_dedup.js, "
    "машина видела 205 != CDN 206 (девиантный урок 156); 114-й КАНДИДАТ "
    "МАТЕРИАЛИЗОВАЛСЯ — median 0.0 ТРИ ПОДРЯД нулевых ранга, реестр "
    "63->64; ген-цепочка gen_206_recover.py (ЕДИНЫЙ PLACEHOLDER-СВАП, "
    "ИНДЕКС-ПИННИНГ ГЕНЕРИАЛИЗОВАН); точек 202 (записей 206); стазис 187)")
out.append(
    "- [окно 207, конденсат] итерация 207: 195-й вердикт ТИХИЙ ПАРИТЕТ "
    "exit 0 БЕЗ заметки (e1b9283 #205 vs ff7b23e копия-2 #204, CLASSIC "
    "СМЕЖНАЯ idx 206 vs 205, distance 1, разброс 3.2 УЗКИЙ — тринадцатая "
    "подряд узкая; откат #21 — ШЕСТОЙ ПОДРЯД; 115-й НЕ материализовался, "
    "реестр 64; gen_207_recover.py, БЕЗ DEDUP — точка и пара РАЗНЫЕ "
    "коммиты; урок 156 рутина: 207 == CDN 207 с первого прогона; точек "
    "203 (записей 207); стазис 188)")
out.append(
    "- [окно 208, конденсат] итерация 208: 196-й вердикт ДРЕЙФ СРЕДЫ "
    "exit 3 (82ccccf #206 vs 1356cac #201, MEDIUM КРОСС-ЗАПИСНАЯ idx 207 "
    "vs 202, distance 5 — 4 CLASSIC между; разброс 89.4 п.п. САМЫЙ "
    "ШИРОКИЙ современной эры — серия 13 узких пар ПРЕРВАЛАСЬ; реестр 64; "
    "код не тронут — СРЕДА)")
out.append(
    "- [окно 229, конденсат] итерация 229: 217-й вердикт РЕГРЕСС exit 1 "
    "(eace4a8 #234 vs 49728a4 #233, CLASSIC СМЕЖНАЯ idx 235 vs 234, "
    "разброс 31.2 ШИРОКИЙ; 8 флагов parse/foxurl/1-13; ДИФФЕРЕНЦИАТОР "
    "url_crate ОБРАТНО; КЛЮЧЕВОЕ ОТКРЫТИЕ: ГЕТЕРОГЕННОСТЬ ПУЛА CLASSIC, "
    "дискриминатор v11/canary OLD 5.57-5.77e-05 vs NEW 6.55-7.65e-05 — "
    "РАЗНЫЕ ХОСТЫ пула (раннер-лотерея), вердикт = кросс-профильная пара, "
    "ОТКАТ КОДА НЕ ТРЕБУЕТСЯ; КОРРЕКЦИЯ КОРИДОРА: CLASSIC 2.2..4.5 валиден "
    "только same-profile; СЧЁТЧИК corpus-all +11.83%, счётчик 10 -> 11; "
    "реестр 68 (137-й НЕ); точек 228 (записей 236); откат #27, ВОСЬМОЙ)")
out.append(full280_282.rstrip())

LOCAL.write_text(local_raw.rstrip() + "\n\n" + "\n".join(out) + "\n",
                 encoding="utf-8")
print(f"OK: локальный worklog восстановлен (было {n_h} '##'-записей эры 188); "
      f"добавлены конденсаты 189-279 ({len(idx)} шт + 229 вручную) и "
      f"ПОЛНЫЕ записи 280/281/282 ({len(full280_282.splitlines())} строк).")
