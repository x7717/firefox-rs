for w in ("Окно 281", "Окно 282", "Окно 283", "Окно 284", "Окно 285",
          "Окно 286", "Окно 287", "Окно 288", "Окно 289", "Окно 290",
          "Окно 291", "Окно 292", "Окно 293", "Окно 294", "Окно 295",
          "Окно 296", "Окно 297"):
    assert w in full280_297, f"нет {w} в полном хвосте"

