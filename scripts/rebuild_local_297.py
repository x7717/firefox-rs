assert n_local == 7810, f"локальный базис {n_local} != 7810 строк"
hdrs = re.findall(r"^## .*Окно (\d+) ", local_raw, re.M)
bad = [int(h) for h in hdrs if int(h) >= 189]
assert not bad, f"локальный worklog НЕ в эре 188: заголовки {bad}"
assert "ПРЕ-РЕГИСТРАЦИЯ ОКНА 188" in local_raw, "эра 188 не опознана"

