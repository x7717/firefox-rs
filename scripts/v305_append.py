wl = Path("WORKLOG.md")
cur = wl.read_text(encoding="utf-8")
if not cur.endswith("\n"):
    cur += "\n"
wl.write_text(cur + entry, encoding="utf-8")
old_n = cur.count("\n")
new_n = (cur + entry).count("\n")
print(f"WORKLOG.md: {old_n} -> {new_n} строк (+{new_n - old_n}); "
      f"запись окна 305 = {entry.count(chr(10))} строк")
